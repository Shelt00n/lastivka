import pg from "pg";
import { mkdirSync } from "node:fs";

/**
 * PostgreSQL access.
 *  - production: a real PostgreSQL server (`DATABASE_URL`, node-postgres pool);
 *  - local dev and tests: PGlite — the same PostgreSQL compiled to WASM, in-process
 *    (persisted to a folder in dev, in memory in tests). Same SQL dialect everywhere.
 *
 * SQL is written with `?` placeholders and converted to `$1..$n` here.
 */

export type SqlParam = string | number | boolean | null;

export interface Db {
  all<T>(sql: string, ...params: SqlParam[]): Promise<T[]>;
  one<T>(sql: string, ...params: SqlParam[]): Promise<T | undefined>;
  /** Returns the number of affected rows. */
  run(sql: string, ...params: SqlParam[]): Promise<number>;
  /** Run fn in a transaction; nested calls reuse the outer transaction. */
  tx<T>(fn: (db: Db) => Promise<T>): Promise<T>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
}

type Query = (text: string, params: SqlParam[]) => Promise<{ rows: unknown[]; rowCount: number }>;

export function toPg(sql: string): string {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

function wrap(query: Query, extra: Pick<Db, "tx" | "exec" | "close">): Db {
  return {
    all: async <T>(sql: string, ...p: SqlParam[]) => (await query(toPg(sql), p)).rows as T[],
    one: async <T>(sql: string, ...p: SqlParam[]) => (await query(toPg(sql), p)).rows[0] as T | undefined,
    run: async (sql, ...p) => (await query(toPg(sql), p)).rowCount,
    ...extra,
  };
}

// BIGINT (ms timestamps, COUNT(*)) → JS number instead of string. Safe for our ranges.
pg.types.setTypeParser(20, (v) => Number(v));

function postgres(url: string): Db {
  const pool = new pg.Pool({ connectionString: url, max: 5, idleTimeoutMillis: 30_000 });
  pool.on("error", (err) => console.error("[pg] idle client error", err.message));
  const viaPool: Query = async (text, params) => {
    const r = await pool.query(text, params);
    return { rows: r.rows, rowCount: r.rowCount ?? 0 };
  };
  const db: Db = wrap(viaPool, {
    async tx(fn) {
      const client = await pool.connect();
      const viaClient: Query = async (text, params) => {
        const r = await client.query(text, params);
        return { rows: r.rows, rowCount: r.rowCount ?? 0 };
      };
      const inner: Db = wrap(viaClient, {
        tx: (f) => f(inner),
        exec: async (sql) => void (await client.query(sql)),
        close: async () => {},
      });
      try {
        await client.query("BEGIN");
        const result = await fn(inner);
        await client.query("COMMIT");
        return result;
      } catch (err) {
        await client.query("ROLLBACK").catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    exec: async (sql) => void (await pool.query(sql)),
    close: () => pool.end(),
  });
  return db;
}

async function pglite(dataDir?: string): Promise<Db> {
  const { PGlite } = await import("@electric-sql/pglite");
  if (dataDir) mkdirSync(dataDir, { recursive: true });
  const lite = new PGlite(dataDir, { parsers: { 20: (v: string) => Number(v) } });
  await lite.waitReady;
  type Lite = Pick<typeof lite, "query">;
  const queryOn =
    (conn: Lite): Query =>
    async (text, params) => {
      const r = await conn.query(text, params);
      return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length };
    };
  return wrap(queryOn(lite), {
    tx: (fn) =>
      lite.transaction(async (t) => {
        const inner: Db = wrap(queryOn(t), {
          tx: (f) => f(inner),
          exec: async (sql) => void (await t.exec(sql)),
          close: async () => {},
        });
        return fn(inner);
      }),
    exec: async (sql) => void (await lite.exec(sql)),
    close: () => lite.close(),
  });
}

/** `DATABASE_URL` → PostgreSQL; otherwise PGlite in `dataDir` (or in memory when omitted). */
export async function openDb(opts: { url?: string; dataDir?: string }): Promise<Db> {
  const db = opts.url ? postgres(opts.url) : await pglite(opts.dataDir);
  await db.exec(SCHEMA);
  return db;
}

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         TEXT NOT NULL,
  display_name     TEXT NOT NULL,
  bio              TEXT NOT NULL DEFAULT '',
  password_hash    TEXT,                          -- NULL for bots and seeded colleagues (cannot log in)
  is_bot           SMALLINT NOT NULL DEFAULT 0,
  is_demo          SMALLINT NOT NULL DEFAULT 0,   -- shared demo accounts: profile/sessions are read-only
  bot_kind         TEXT,
  avatar_hue       INTEGER NOT NULL DEFAULT 210,
  time_zone        TEXT NOT NULL DEFAULT 'Europe/Kyiv',
  quiet_enabled    SMALLINT NOT NULL DEFAULT 0,
  quiet_start      INTEGER NOT NULL DEFAULT 1380,
  quiet_end        INTEGER NOT NULL DEFAULT 480,
  show_local_time  SMALLINT NOT NULL DEFAULT 1,
  last_seen_at     BIGINT,
  created_at       BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));

CREATE TABLE IF NOT EXISTS sessions (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash       TEXT NOT NULL UNIQUE,          -- sha256 of the cookie token; the raw token is never stored
  user_agent       TEXT NOT NULL DEFAULT '',
  created_at       BIGINT NOT NULL,
  last_active_at   BIGINT NOT NULL,
  expires_at       BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS chats (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type             TEXT NOT NULL CHECK (type IN ('private', 'group')),
  title            TEXT,
  private_key      TEXT UNIQUE,                   -- "minUserId:maxUserId" — one private chat per pair
  avatar_hue       INTEGER NOT NULL DEFAULT 200,
  created_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at       BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_members (
  chat_id          INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role             TEXT NOT NULL DEFAULT 'member',
  joined_at        BIGINT NOT NULL,
  last_read_at     BIGINT NOT NULL DEFAULT 0,
  pinned           SMALLINT NOT NULL DEFAULT 0,
  muted            SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (chat_id, user_id)
);
CREATE INDEX IF NOT EXISTS chat_members_user ON chat_members(user_id);

CREATE TABLE IF NOT EXISTS messages (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id          INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  sender_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  text             TEXT NOT NULL,
  reply_to_id      INTEGER REFERENCES messages(id) ON DELETE SET NULL,
  buttons          TEXT,                          -- JSON array (bot reply keyboard)
  created_at       BIGINT NOT NULL,
  edited_at        BIGINT,
  deliver_at       BIGINT                         -- NOT NULL = held by quiet hours, visible only to the sender
);
CREATE INDEX IF NOT EXISTS messages_chat_time ON messages(chat_id, created_at, id);
CREATE INDEX IF NOT EXISTS messages_pending ON messages(deliver_at) WHERE deliver_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS reactions (
  message_id       INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  emoji            TEXT NOT NULL,
  created_at       BIGINT NOT NULL,
  PRIMARY KEY (message_id, user_id)
);
`;

export const TABLES = ["reactions", "messages", "chat_members", "chats", "sessions", "users"];
